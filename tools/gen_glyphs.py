#!/usr/bin/env python3
"""Writes src/chant/glyphs.ts from the Greciliae font: the codepoint and advance of
each glyph the staff renderer uses. Run again after adding names to GLYPHS below.

  python3 tools/gen_glyphs.py assets/fonts/greciliae.ttf > src/chant/glyphs.ts
"""
import sys
from fontTools.ttLib import TTFont

GLYPHS = [
    'Punctum', 'Virga', 'CClef', 'FClef', 'Flat', 'Natural',
    'CustosUpShort', 'CustosUpMedium', 'CustosUpLong',
    'CustosDownShort', 'CustosDownMedium', 'CustosDownLong',
    'DivisioMinimaFour', 'DivisioMinorFour', 'DivisioMaiorFour',
    'AuctumMora',
]

font = TTFont(sys.argv[1])
cmap = {name: cp for cp, name in font.getBestCmap().items()}
glyf, hmtx = font['glyf'], font['hmtx']

print('// Generated by tools/gen_glyphs.py from the Greciliae font. Do not edit by hand.')
print('export interface Glyph {')
print('  /** The character that draws the glyph in the font. */')
print('  char: string;')
print('  /** Horizontal advance in font units (1000 to the em). */')
print('  advance: number;')
print('}')
print()
print('export const GLYPHS = {')
for name in GLYPHS:
    print(f"  {name}: {{ char: '\\u{cmap[name]:04X}', advance: {hmtx[name][0]} }},")
print('} as const satisfies Record<string, Glyph>;')
print()
print('export type GlyphName = keyof typeof GLYPHS;')
