#!/usr/bin/env python3
"""Writes src/chant/neumeTable.ts: which Greciliae glyph draws each group of two or
three notes. GregorioTeX picks the glyph from the shape and the height of the
notes (a long tail or not, which of the five widths), so this asks the `gregorio`
compiler about every group the 4-line staff allows and writes down its answers.

  python3 tools/gen_neumes.py assets/fonts/greciliae.ttf > src/chant/neumeTable.ts

Needs `gregorio` (6.1) on the PATH.
"""
import os
import re
import subprocess
import sys
import tempfile

from fontTools.ttLib import TTFont

LETTERS = 'abcdefghijklm'  # heights 3..15, the pitches a 4-line staff allows
LOW, HIGH = 3, 15
SHAPES = {'pes': 'Pes', 'flexus': 'Flexus', 'torculus': 'Torculus', 'porrectus': 'Porrectus', 'scandicus': 'Scandicus'}
NAME = re.compile(r'^(Pes|Flexus|Torculus|Porrectus|Scandicus)(Longqueue|Openqueue)?((?:One|Two|Three|Four|Five)+)Nothing$')


def letter(height):
    return LETTERS[height - LOW]


def cases():
    """Every group as (shape, first height, intervals, heights of its notes)."""
    for h in range(LOW, HIGH + 1):
        for a in range(1, 6):
            if h + a <= HIGH:
                yield 'pes', h, (a,), (h, h + a)
            if h - a >= LOW:
                yield 'flexus', h, (a,), (h, h - a)
        for x in range(1, 6):
            for y in range(1, 6):
                if h + x <= HIGH and h + x - y >= LOW:
                    yield 'torculus', h, (x, y), (h, h + x, h + x - y)
                if h - x >= LOW and h - x + y <= HIGH:
                    yield 'porrectus', h, (x, y), (h, h - x, h - x + y)
                if h + x + y <= HIGH:
                    yield 'scandicus', h, (x, y), (h, h + x, h + x + y)


def ask_gregorio(groups):
    gabc = 'name: neumes;\n%%\n(c4) ' + ' '.join(
        'A(' + ''.join(letter(n) for n in notes) + ')' for _, _, _, notes in groups) + ' (::)\n'
    # gregorio will only write beside where it runs, so run it in a scratch folder
    with tempfile.TemporaryDirectory() as tmp:
        with open(os.path.join(tmp, 'n.gabc'), 'w') as f:
            f.write(gabc)
        done = subprocess.run(['gregorio', '-o', 'n.gtex', 'n.gabc'], cwd=tmp, capture_output=True, text=True)
        if 'error' in done.stderr:
            sys.exit(done.stderr)
        with open(os.path.join(tmp, 'n.gtex')) as f:
            gtex = f.read()
    syllables = re.split(r'\\GreSyllableNoteCount\{(\d+)\}', gtex)[1:]
    answers = []
    for count, body in zip(syllables[::2], syllables[1::2]):
        body = body.split('\\GreSyllable{')[0]
        answers.append((int(count), re.findall(r'\\GreGlyph\{\\GreCP(\w+)\}\{(\d+)\}', body)))
    return answers


groups = list(cases())
answers = ask_gregorio(groups)
assert len(answers) == len(groups), (len(answers), len(groups))

font = TTFont(sys.argv[1])
cmap = {name: cp for cp, name in font.getBestCmap().items()}
hmtx = font['hmtx']

glyphs, index, table = [], {}, {}
for (shape, h, intervals, notes), (count, found) in zip(groups, answers):
    # gregorio splits a group it has no single glyph for; leave those out
    if count != len(notes) or len(found) != 1:
        continue
    name, height = found[0]
    match = NAME.match(name)
    assert match and match.group(1) == SHAPES[shape] and int(height) == h, (shape, h, intervals, name, height)
    if name not in index:
        index[name] = len(glyphs)
        glyphs.append(name)
    table[f"{shape}:{h - 6}:{'-'.join(map(str, intervals))}"] = index[name]

print('// Generated by tools/gen_neumes.py from gregorio and the Greciliae font. Do not edit by hand.')
print('export interface NeumeGlyph {')
print('  /** The character that draws the glyph in the font. */')
print('  char: string;')
print('  /** Horizontal advance in font units (1000 to the em). */')
print('  advance: number;')
print('}')
print()
print('/** The glyphs used below. */')
print('export const NEUME_GLYPHS: NeumeGlyph[] = [')
for name in glyphs:
    print(f"  {{ char: '\\u{cmap[name]:04X}', advance: {hmtx[name][0]} }}, // {name}")
print('];')
print()
print('/**')
print(' * The glyph for a group, as an index into NEUME_GLYPHS, keyed by')
print(' * "shape:position of the first note:steps between the notes", where the')
print(' * position counts staff steps up from the bottom line and each interval is')
print(' * a number of steps (always positive; the shape says which way it goes).')
print(' */')
print('export const NEUME_TABLE: Record<string, number> = {')
line = ''
for key, value in table.items():
    item = f"'{key}': {value}, "
    if len(line) + len(item) > 100:
        print('  ' + line.rstrip())
        line = ''
    line += item
print('  ' + line.rstrip())
print('};')
